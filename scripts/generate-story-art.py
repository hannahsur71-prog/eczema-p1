#!/usr/bin/env python3
"""Converts the prototype's story drawings (covers, the home banner and the scenes behind the massage guide) into Swift.
These are placeholder illustrations; replace them with final art when it is ready.
Usage: python3 scripts/generate-story-art.py <App.dc.html> > Alji/Main/StoryArtData.swift
Needs: node, and pip install fonttools"""
import json, os, subprocess, sys
src = open(os.path.join(os.path.dirname(__file__), 'generate-onboarding-art.py')).read()
exec(src[:src.index("main = open(sys.argv[1])")])
app = open(sys.argv[1]).read()
# The drawing code in the prototype, from its helpers to the end of the motif table.
a = app.index('const szStar = '); b = app.index('const coverShapes = ')
js = app[a:b] + """
const ids = ['comet','lastStar','tummyStory','flareStory','sleepy','littleStar','whale','bear','feelings','loved','emotions','positive','valuable','brave','calm','kind','enough','parentCalm','breathe','fallback'];
const out = {}; ids.forEach((id) => { out[id] = motif(id, 'BLOB'); }); console.log(JSON.stringify(out));
"""
motifs = json.loads(subprocess.run(['node', '-e', js], capture_output=True, text=True, check=True).stdout)
def markup(shapes):
    return ''.join('<path d="%s" fill="%s" stroke="%s" stroke-width="%s" opacity="%s"/>' % (s['d'], s['fill'], s['stroke'], s['sw'] or 1, s['op']) for s in shapes)
out = ["// Generated by scripts/generate-story-art.py from the approved prototype. Do not edit by hand.",
       "// Placeholder illustrations, drawn in a 150 × 190 space. Shapes marked special 2 take the story's own color.",
       "import Foundation", "", "enum StoryArtData {"]
for name, shapes in motifs.items():
    out.append(swift(name, convert(markup(shapes))))
out.append("")
out.append("    static let motifs: [String: [ArtShape]] = [" + ", ".join('"%s": %s' % (k, k) for k in motifs if k != 'fallback') + "]")
out.append("}")
print('\n'.join(out))
