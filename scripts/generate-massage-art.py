#!/usr/bin/env python3
"""Converts the massage player's drawings (front body, foot, palm, thumb) from the prototype into Swift.
Usage: python3 scripts/generate-massage-art.py <App.dc.html> > Alji/Main/MassageArtData.swift"""
import re, sys, os
src = open(os.path.join(os.path.dirname(__file__), 'generate-onboarding-art.py')).read()
exec(src[:src.index("main = open(sys.argv[1])")])
app = open(sys.argv[1]).read()
def inner(flag):
    a = app.index('<sc-if value="{{ %s }}"' % flag); a = app.index('>', a) + 1
    return app[a:app.index('</sc-if>', a)]
front = inner('viewFront')
foot = re.sub(r'<defs>.*?</defs>', '', inner('viewFoot'), flags=re.S)
foot = re.sub(r'<path[^>]*url\(#aljiSole\)[^>]*></path>', '', foot)
palm = inner('viewPalm')
ti = app.index('<g transform="scale(1.35)"'); thumb = app[ti:app.index('</g>', ti) + 4]
clean = lambda s: re.sub(r'\sstyle="[^"]*"', '', s)
out = ["// Generated by scripts/generate-massage-art.py from the approved prototype. Do not edit by hand.", "import Foundation", "",
       "extension ArtData {",
       "    /// The thumb is drawn tip-up; its pad sits at `thumbAnchor`.", "    static let thumbSize = CGSize(width: 24, height: 44)", "    static let thumbAnchor = CGPoint(x: 12, y: 22)", ""]
out.append(swift('bodyFront', convert(clean(front)))); out.append(swift('foot', convert(clean(foot))))
out.append(swift('palm', convert(clean(palm)))); out.append(swift('thumb', convert(clean(thumb), Identity.translate(12, 22))))
out.append("}"); print('\n'.join(out))
